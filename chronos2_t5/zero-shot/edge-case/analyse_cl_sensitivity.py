"""E9 sensitivity check -- does the cross-learning gain depend on the four small datasets?

Four of the 25 datasets hold fewer than the 100 series that `CROSS_LEARNING_BATCH`
allows: `monash_australian_electricity` (5), `ercot` (8), `exchange_rate` (8) and
`monash_cif_2016` (72). Those are the complete datasets, not samples. Because a target
grouped with its OWN dataset gets a group of whatever size that dataset has, while the
two foreign conditions are always topped up to exactly 100, the native-vs-foreign
contrast varies group size alongside group membership for these four. This script asks
whether the E9 conclusions survive when they are removed.

It deliberately imports `holm`, `boot_ci`, `ARMS` and `NBOOT` from `analyse_cl_shuffle`
rather than restating them, so the two analyses cannot drift apart. `analyse_cl_shuffle`
draws its bootstrap from a module-level generator seeded once, so this script resets that
generator before each block; the "ALL datasets" block therefore reproduces the published
CL_SHUFFLE_ANALYSIS_<metric>.md numbers exactly, which is the check that the replication
is faithful.

Reads:   results/crosslearning_shuffle.csv
Writes:  results/CL_SENSITIVITY_ANALYSIS.md   (both metrics, both subsets, one file)

Run:  python analyse_cl_sensitivity.py
"""
from __future__ import annotations

from pathlib import Path
import datetime as _dt

import numpy as np
import pandas as pd
from scipy.stats import gmean, wilcoxon, binomtest

import analyse_cl_shuffle as A          # single source of truth for the statistics

HERE = Path(__file__).resolve().parent
OUT = HERE / "results"
CSV = OUT / "crosslearning_shuffle.csv"
FULL_GROUP = 100                        # = R2.CROSS_LEARNING_BATCH


def load(metric: str) -> pd.DataFrame:
    """E9's own pivot, plus the per-dataset series count the pivot drops."""
    df = pd.read_csv(CSV)
    n_ser = df.groupby("dataset")["n_series"].first()
    piv = df.pivot_table(index=["dataset", "freq"], columns="arm", values=metric).reset_index()
    for arm in A.ARMS:
        if arm in piv:
            piv[f"gain_{arm}"] = piv["univariate"] / piv[arm]
    piv["n_series"] = piv["dataset"].map(n_ser)
    return piv


def block(g: pd.DataFrame):
    """Per-condition gains and paired contrasts, exactly as analyse_cl_shuffle does."""
    A.RNG = np.random.default_rng(0)     # reset so blocks are comparable and reproducible
    rows = []
    for arm in A.ARMS:
        v = g[f"gain_{arm}"].dropna()
        lo, hi = A.boot_ci(v)
        wins = int((v > 1).sum())
        rows.append({"condition": arm, "n": len(v), "gain_gmean": gmean(v),
                     "ci_lo": lo, "ci_hi": hi, "helped": f"{wins}/{len(v)}",
                     "sign_p": binomtest(wins, len(v), 0.5, alternative="greater").pvalue,
                     "ci_clears_1": bool(lo > 1.0)})
    per_arm = pd.DataFrame(rows)

    cons, ps = [], []
    for a, b in (("native", "foreign_samefreq"), ("native", "foreign_difffreq"),
                 ("foreign_samefreq", "foreign_difffreq")):
        j = g[[f"gain_{a}", f"gain_{b}"]].dropna()
        w = wilcoxon(j[f"gain_{a}"], j[f"gain_{b}"])
        cons.append({"contrast": f"{a} vs {b}", "n": len(j),
                     "median_diff": float((j[f"gain_{a}"] - j[f"gain_{b}"]).median()),
                     "p": float(w.pvalue)})
        ps.append(w.pvalue)
    C = pd.DataFrame(cons)
    C["p_holm"] = A.holm(ps)
    return per_arm, C


def main():
    stamp = _dt.datetime.fromtimestamp(CSV.stat().st_mtime).strftime("%Y-%m-%d %H:%M")
    lines = [
        "# E9 sensitivity -- the four datasets with fewer than 100 series", "",
        "Gain = univariate metric divided by cross-learning metric; above 1 means grouping",
        "helped. Analysis unit is the dataset; CIs bootstrap the datasets "
        f"({A.NBOOT} draws, seed 0); contrasts are paired Wilcoxon with Holm correction.",
        "Definitions are imported from `analyse_cl_shuffle.py`, not restated, so the two",
        "analyses cannot drift apart. The ALL-datasets blocks reproduce",
        "`CL_SHUFFLE_ANALYSIS_<metric>.md` exactly.", "",
        f"Source: `results/{CSV.name}` (last modified {stamp}). "
        f"Generated by `analyse_cl_sensitivity.py`.", "",
        "## Why these four are a confound", "",
        "A target grouped with its own dataset's series gets a group of whatever size that",
        "dataset has; the two foreign conditions are always filled to exactly "
        f"{FULL_GROUP} series.",
        "For the datasets below the two settings therefore differ in group size as well as",
        "in which series share the group.", "",
    ]

    g0 = load("MASE")
    small = g0.loc[g0.n_series < FULL_GROUP, ["dataset", "freq", "n_series"]] \
              .sort_values("n_series")
    lines += [small.to_markdown(index=False), ""]

    for metric in ("MASE", "WQL"):
        g = load(metric)
        for tag, sub in (("all datasets", g),
                         (f"only datasets with {FULL_GROUP} series",
                          g[g.n_series == FULL_GROUP].reset_index(drop=True))):
            per_arm, C = block(sub)
            lines += [f"## {metric} -- {tag} (n = {len(sub)})", "",
                      per_arm.round(4).to_markdown(index=False), "",
                      C.round(4).to_markdown(index=False), ""]
            print(f"\n### {metric} -- {tag} (n = {len(sub)})")
            print(per_arm.round(4).to_string(index=False))
            print(C.round(4).to_string(index=False))

    md = OUT / "CL_SENSITIVITY_ANALYSIS.md"
    md.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print(f"\n-> {md}")


if __name__ == "__main__":
    main()
